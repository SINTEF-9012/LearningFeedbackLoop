@router.post("/experiment/run-live-breakage")
async def trigger_live_breakage_experiment(
    request: Request,
    body: Dict[str, Any] = Body(default={}),
):
    """Run a breakage experiment **in-process** with real-time WebSocket progress.

    Returns immediately with ``{run_id, ws_url, status}`` so the client can
    connect to the shared progress WebSocket.  The actual experiment runs as
    a background asyncio Task.

    Body parameters
    ---------------
    run_id : str, optional
        If omitted a unique id is generated.
    dataset : str
        ``"site_a_line2"`` (default) or ``"casedata"``.
    csv : str, optional
        Explicit CSV path for breakage features.
    split_name : str, optional
        Split bundle under ``data/breakage_patterns/splits/``. Defaults to
        the Excel-anchored PART0001 split for Site_a_line2 when no CSV is given.
    sandbox_priors : bool
        Snapshot & restore priors (default True).
    """
    from .breakage_experiment_runner import LiveBreakageExperimentRunner

    run_id = body.pop("run_id", None) or f"breakage_{datetime.now().strftime('%Y-%m-%d_%H%M')}"
    sandbox = body.pop("sandbox_priors", True)
    dataset = body.pop("dataset", "site_a_line2")
    csv_path = body.pop("csv", None) or body.pop("csv_path", None)
    label_scheme = body.pop("label_scheme", "original")
    split_name = body.pop("split_name", None)
    # Remaining body keys are ExperimentConfig overrides (feedback realism, etc.)
    config_overrides = _harden_live_breakage_config_overrides(
        run_id=run_id,
        request=request,
        config_overrides=dict(body),
    )

    if run_id in _active_live_runs and not _active_live_runs[run_id].done():
        raise HTTPException(status_code=409, detail=f"Run {run_id} is already in progress")

    runner = LiveBreakageExperimentRunner(
        dataset=dataset,
        run_id=run_id,
        sandbox_priors=sandbox,
        csv_path=csv_path,
        label_scheme=label_scheme,
        split_name=split_name,
        config_overrides=config_overrides,
    )

    async def _run_breakage_and_cleanup():
        from backend.events import bus
        # Give the client a moment to connect its WebSocket
        await asyncio.sleep(1.0)

        # Pre-experiment snapshot
        _capture_neo4j_snapshot(run_id=run_id, label=f"pre:{run_id}")

        try:
            result = await runner.execute()
            logger.info("Live breakage experiment %s finished: success=%s", run_id, result.get("success"))

            if not result.get("success"):
                error_msg = result.get("error", "Unknown error")
                logger.error("Breakage experiment %s failed: %s", run_id, error_msg)
                _save_error_results(run_id, "breakage", result)
                await bus.publish(
                    f"experiment.{run_id}",
                    {
                        "run_id": run_id,
                        "phase": "error",
                        "status": "error",
                        "message": f"Experiment failed: {error_msg}",
                        "pct": 0,
                        "elapsed_s": 0,
                        "detail": {"error": error_msg},
                    },
                )
            else:
                # Push experiment summary to SINDIT KG if bridge is available
                await _push_experiment_to_sindit(
                    run_id=run_id,
                    experiment_type="breakage",
                    result=result,
                )

                # Push experiment sub-graph to Neo4j
                _push_experiment_to_neo4j(
                    run_id=run_id,
                    experiment_type="breakage",
                    result=result,
                )
        except Exception:
            logger.exception("Live breakage experiment %s failed", run_id)
        finally:
            _active_live_runs.pop(run_id, None)

    task = asyncio.create_task(_run_breakage_and_cleanup())
    _active_live_runs[run_id] = task

    return {
        "run_id": run_id,
        "ws_url": f"/ws/agent/memory/experiment/progress/{run_id}",
        "status": "started",
        "experiment_type": "breakage",
    }


