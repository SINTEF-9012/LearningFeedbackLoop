@router.post("/experiment/run")
async def trigger_experiment_run(
    body: Dict[str, Any] = Body(default={}),
):
    """Trigger a new experiment run as a subprocess.

    Accepts optional parameters that map to run_stoppage_experiment.py flags.
    Returns ``{success, stdout, stderr}`` when the subprocess completes.
    """
    import sys
    cmd = [
        sys.executable, "-m", "scripts.run_stoppage_experiment",
    ]

    # Map body params to CLI flags
    if body.get("single"):
        cmd.append("--single")
    if body.get("rotate"):
        cmd.append("--rotate")

    gap = body.get("gap") or body.get("gap_s") or body.get("prediction_gap_s")
    if gap is not None:
        cmd.extend(["--gap", str(gap)])

    gap_sweep = body.get("gap_sweep")
    if gap_sweep and isinstance(gap_sweep, list):
        cmd.append("--gap-sweep")
        cmd.extend([str(g) for g in gap_sweep])

    variant = body.get("variant") or body.get("eval_variant")
    if variant:
        cmd.extend(["--variant", str(variant)])

    noise_rate = body.get("noise_rate")
    if noise_rate is not None:
        cmd.extend(["--noise-rate", str(noise_rate)])

    feedback_every = body.get("feedback_every") or body.get("feedback_every_n")
    if feedback_every is not None:
        cmd.extend(["--feedback-every", str(feedback_every)])

    train_ops = body.get("train_ops")
    if train_ops and isinstance(train_ops, list):
        cmd.append("--train-ops")
        cmd.extend(train_ops)

    test_op = body.get("test_op")
    if test_op:
        cmd.extend(["--test-op", str(test_op)])

    eval_op = body.get("eval_op")
    if eval_op:
        cmd.extend(["--eval-op", str(eval_op)])

    # API mode: route experiment events through the live backend API
    if body.get("api_mode"):
        cmd.append("--api-mode")
        api_url = body.get("api_url")
        if api_url:
            cmd.extend(["--api-url", str(api_url)])
    if body.get("sindit_live"):
        cmd.append("--sindit-live")

    downsample = body.get("downsample")
    if downsample:
        cmd.extend(["--downsample", str(downsample)])

    # Window & sample-rate passthrough (align experiment with extraction)
    window = body.get("window") or body.get("window_size_s")
    if window is not None:
        cmd.extend(["--window", str(window)])

    hz = body.get("hz") or body.get("sample_rate_hz")
    if hz is not None:
        cmd.extend(["--hz", str(hz)])

    # Sandboxed priors path — prevents contamination of production priors
    priors_path = body.get("priors_path")
    if priors_path:
        cmd.extend(["--priors-path", str(priors_path)])

    logger.info("Triggering experiment: %s", " ".join(cmd))

    try:
        proc = await asyncio.create_subprocess_exec(
            *cmd,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
            cwd=str(_PROJECT_ROOT),
        )
        stdout_bytes, stderr_bytes = await asyncio.wait_for(
            proc.communicate(), timeout=600,  # 10 minute timeout
        )
        stdout_str = stdout_bytes.decode("utf-8", errors="replace")[-8000:]  # last 8KB
        stderr_str = stderr_bytes.decode("utf-8", errors="replace")[-4000:]

        # After experiment completes, refresh scorer priors from disk
        # so the live /scorer/priors endpoint reflects experiment results.
        if proc.returncode == 0:
            try:
                orch = get_orchestrator()
                if hasattr(orch.scorer, "refresh_priors"):
                    orch.scorer.refresh_priors()
                    logger.info("Scorer priors refreshed from disk after experiment run")
                elif hasattr(orch.scorer, "_load_priors"):
                    orch.scorer._load_priors()
                    logger.info("Scorer priors reloaded from disk after experiment run")
            except Exception:
                logger.debug("Failed to refresh scorer priors after experiment", exc_info=True)

        return {
            "success": proc.returncode == 0,
            "stdout": stdout_str,
            "stderr": stderr_str,
        }
    except asyncio.TimeoutError:
        raise HTTPException(status_code=504, detail="Experiment timed out (>10 min)")
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Failed to start experiment: {exc}")


