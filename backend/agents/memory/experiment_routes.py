    """List all experiment runs found on disk.

    Scans both ``data/breakage_patterns/stoppage_experiment/`` and
    ``data/experiment_snapshots/`` for sub-directories containing
    ``experiment_results.json``, including nested live-run directories.
    """
    # Also include any live runs that are currently executing
    _live_run_ids = set(_active_live_runs.keys())

    runs: List[Dict[str, Any]] = []
    seen: set[str] = set()
    for root in _ALL_EXPERIMENT_ROOTS:
        if not root.is_dir():
            continue
        for results_file in root.rglob("experiment_results.json"):
            d = results_file.parent
            # Build a run_id from the relative path (handles nested live dirs)
            run_id = _run_id_from_dir(d)
            if run_id in seen:
                continue
            seen.add(run_id)
            data = _load_run_json(d)
            if data is None:
                continue
