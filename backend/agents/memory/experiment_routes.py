@router.post("/experiment/review", response_model=ExperimentReviewResponse)
async def review_experiment_results(request: ExperimentReviewRequest):
    """Bridge experiment results into the live feedback loop.

    This is the critical connection between offline experiments and the live
    pipeline. When an operator reviews experiment results and confirms or
    dismisses detected events, those decisions update the LIVE priors and
    can trigger model retraining — so the experiment directly improves the
    production system.
    """
    orch = get_orchestrator()
    from .retrainer import get_retrainer

    retrainer = get_retrainer(
        model_path=(
            pathlib.Path(orch.config.seed_model_path)
            if getattr(orch.config, "seed_model_path", None) else None
        ),
        model_confidence_path=getattr(orch.scorer, "_model_confidence_path", None),
    )
    updated = 0
    failed = 0
    prior_changes: Dict[str, float] = {}

    # Try to load feature vectors from the experiment run so that
    # retrainer.record_feedback() receives actual feature data.
    _feature_cache: Dict[str, Any] = {}  # sample_id -> np.ndarray
    if request.run_id:
        try:
            import numpy as _np
            import pandas as _pd
            from backend.agents.processing.classical_models import features_from_dict
            from backend.agents.processing.breakage_detector import BreakageFeatureExtractor

            run_dir = _resolve_run_dir(request.run_id)
            data = _load_run_json(run_dir)
            if data:
                cfg = data.get("config", {})
                csv_path = cfg.get("features_csv", "")
                if csv_path and pathlib.Path(csv_path).is_file():
                    df = _pd.read_csv(csv_path)
                    for _, row in df.iterrows():
                        sid = str(row.get("sample_id", row.get("operation", "")))
                        try:
                            feats = features_from_dict(
                                BreakageFeatureExtractor.row_to_feature_dict(row)
                            )
                            _feature_cache[sid] = _np.asarray(feats)
                        except Exception:
                            pass
        except Exception:
            logger.debug("Could not load feature vectors for retrainer", exc_info=True)

    for review in request.reviews:
        try:
            was_significant = review.action == "confirm"

            # Apply feedback to memory via feedback_handler.
            # process_feedback internally calls _handle_confirm/_handle_dismiss
            # which already invokes scorer.update_pattern_prior() for each pattern.
            if review.memory_id and orch.feedback_handler:
                fb_request = MemoryFeedbackRequest(
                    action=FeedbackAction.CONFIRM if was_significant else FeedbackAction.DISMISS,
                    user_id="experiment_reviewer",
                    reason=review.reason or f"Experiment review (run={request.run_id})",
                )
                await orch.feedback_handler.process_feedback(review.memory_id, fb_request)
            else:
                # No memory_id — update priors directly for each pattern key
                for pk in review.pattern_keys:
                    if orch.scorer and hasattr(orch.scorer, 'update_pattern_prior'):
                        orch.scorer.update_pattern_prior(pk, was_significant)

            # Feed features to retrainer so experiment reviews
            # contribute to the model retraining buffer.
            feat_vec = _feature_cache.get(review.sample_id or "")
            if feat_vec is not None:
                retrainer.record_feedback(
                    features=feat_vec,
                    is_significant=was_significant,
                    pattern_keys=review.pattern_keys,
                    memory_id=review.memory_id or "",
                )

            # Read back prior changes for the response
            for pk in review.pattern_keys:
                old_prior = prior_changes.get(pk)  # may not exist yet
                new_prior = orch.scorer.get_pattern_prior(pk) if orch.scorer else 0.5
                prior_changes[pk] = round(new_prior - 0.5, 4)  # delta from neutral

            updated += 1
        except Exception as e:
            logger.warning(f"Failed to process review for {review.sample_id}: {e}")
            failed += 1

    # Check if retraining was triggered
    retrain_triggered = retrainer.should_retrain()
    if retrain_triggered:
        try:
            result = retrainer.retrain()
            logger.info("Experiment review triggered retrain: %s", result.message)
        except Exception:
            pass

    return ExperimentReviewResponse(
        updated=updated,
        failed=failed,
        prior_changes=prior_changes,
        retrain_triggered=retrain_triggered,
        message=f"Processed {updated} reviews ({failed} failed). "
                f"Prior changes: {len(prior_changes)} patterns affected.",
    )


