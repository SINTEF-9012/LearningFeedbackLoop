def _push_experiment_to_neo4j(
    run_id: str,
    experiment_type: str,
    result: Dict[str, Any],
) -> None:
    """Create an :Experiment node in Neo4j and link it to its Sessions/Patterns.

    Called after a successful experiment to populate the per-experiment
    sub-graph that ``get_experiment_graph()`` later queries.
    """
    orchestrator = get_orchestrator()
    store = orchestrator.store
    if not hasattr(store, "store_experiment"):
        logger.debug("Neo4j store not available — skipping experiment graph push")
        return

    try:
        # Collect session IDs from the experiment result
        session_ids: List[str] = []
        for phase_key in ("train_phase", "test_phase", "eval_phase", "training", "test", "eval"):
            phase_data = result.get(phase_key) or {}
            for sample in phase_data.get("samples", []):
                sid = sample.get("session_id") or sample.get("op_id") or sample.get("tool_number")
                if sid:
                    session_ids.append(str(sid))

        # Also extract from top-level config / folds
        config = result.get("config") or result.get("parameters") or {}

        # Metrics
        test_m = result.get("test_phase", {}).get("metrics") or result.get("test", {}).get("metrics") or {}
        eval_m = result.get("eval_phase", {}).get("metrics") or result.get("eval", {}).get("metrics") or {}
        comparison = result.get("comparison") or {}

        store.store_experiment(
            run_id=run_id,
            experiment_type=experiment_type,
            config=config,
            test_metrics=test_m,
            eval_metrics=eval_m,
            comparison=comparison,
            session_ids=list(set(session_ids)),  # dedupe
        )
        logger.info("Pushed experiment %s to Neo4j graph", run_id)

        # Capture post-experiment snapshot
        _capture_neo4j_snapshot(run_id=run_id, label=f"post:{run_id}")

        # Run time-decay on co-occurrence edges to keep the graph
        # focused on the current operating regime.
        if hasattr(store, "decay_old_co_occurrence"):
            try:
                store.decay_old_co_occurrence()
            except Exception:
                logger.debug("Post-experiment co-occurrence decay failed", exc_info=True)
    except Exception:
        logger.exception("Failed to push experiment %s to Neo4j", run_id)


def _capture_neo4j_snapshot(
    *,
    run_id: Optional[str] = None,
    label: Optional[str] = None,
) -> Optional[str]:
    """Best-effort snapshot capture.  Returns snapshot ID or None."""
    orchestrator = get_orchestrator()
    store = orchestrator.store
    if not hasattr(store, "capture_snapshot"):
        return None
    try:
        snap_id = store.capture_snapshot(run_id=run_id, label=label)
        logger.info("Captured graph snapshot %s (label=%s)", snap_id, label)
        return snap_id
    except Exception:
        logger.debug("Snapshot capture failed", exc_info=True)
        return None


async def _push_experiment_to_sindit(
    run_id: str,
    experiment_type: str,
    result: Dict[str, Any],
) -> None:
    """Push experiment results to SINDIT KG as a connected sub-graph.

    Graph structure (all nodes are assets so GraphDB can visualise them)::

        Machine ──[hasExperiment]──→ Experiment
        Experiment ──[hasTestPhase]──→ TestPhase   (metrics as properties)
        Experiment ──[hasEvalPhase]──→ EvalPhase   (metrics as properties)
        EvalPhase  ──[improvedOver]──→ TestPhase
        Experiment ──[analyzedOperation]──→ OperationN …
        Experiment ──[detectedPattern]──→ PatternX …

    This is a best-effort operation — failures are logged but never raised.
    """
    # Experiment/pattern provenance is written as AbstractAsset nodes, which
    # pollutes the physical-asset twin (ISS-46). Opt-in only — off by default so
    # running experiments never dirties the asset graph.
    if os.environ.get("SINDIT_PUSH_EXPERIMENTS", "false").lower() not in ("1", "true", "yes"):
        logger.debug("SINDIT_PUSH_EXPERIMENTS disabled — skipping experiment push")
        return
    if not result.get("success"):
        return

    try:
        sindit_url = os.environ.get("SINDIT_API_URL", "http://localhost:9017")
        sindit_enabled = os.environ.get("SINDIT_ENABLED", "false").lower() in ("1", "true", "yes")
        if not sindit_enabled:
            logger.debug("SINDIT not enabled — skipping experiment push")
            return

        from backend.agents.sindit.client import SinditClient

        async with SinditClient(base_url=sindit_url) as client:
            username = os.environ.get("SINDIT_USERNAME", "sindit")
            password = os.environ.get("SINDIT_PASSWORD", "sindit")
            ok = await client.authenticate(username, password)
            if not ok:
                logger.warning("SINDIT auth failed — cannot push experiment %s", run_id)
                return

            _ASSET_TYPE = "urn:samm:sindit.sintef.no:1.0.0#AbstractAsset"
            machine_uri = "urn:lfl:asset:cnc-machine-1"
            exp_uri = f"urn:lfl:experiment:{run_id}"
            test_uri = f"{exp_uri}:test-phase"
            eval_uri = f"{exp_uri}:eval-phase"
            ts = datetime.now().isoformat()

            # ── Helper: ensure machine asset exists ──────────────────
            existing = await client.get_node(machine_uri, depth=0)
            if not existing:
                await client.post_asset({
                    "uri": machine_uri,
                    "label": "CNC Machine 1",
                    "assetType": _ASSET_TYPE,
                    "assetDescription": "CNC machine monitored by the LFL system.",
                })

            # ── 1. Experiment-run asset ──────────────────────────────
            await client.post_asset({
                "uri": exp_uri,
                "label": f"{experiment_type.title()} Experiment — {run_id}",
                "assetType": _ASSET_TYPE,
                "assetDescription": (
                    f"LFL {experiment_type} experiment run. "
                    f"Methodology: 3-phase (train → test-baseline → eval-feedback)."
                ),
            })

            # ── 2. Phase assets + metric properties ──────────────────
            def _phase_props(
                prefix: str, data: Dict[str, Any], asset_uri: str,
            ) -> None:
                """Return list of property dicts to create."""
                out = []
                for key in ("f1", "precision", "recall", "auc_roc",
                            "n_samples", "n_flagged", "n_feedback",
                            "n_predictions_flipped", "n_model_retrains"):
                    val = data.get(key)
                    if val is None:
                        continue
                    str_val = str(round(val, 4)) if isinstance(val, float) else str(val)
                    out.append({
                        "uri": f"{asset_uri}:{key}",
                        "label": key.replace("_", " ").title(),
                        "propertyName": key,
                        "propertyValue": str_val,
                        "propertyUnit": "",
                        "propertyDataType": "float" if isinstance(val, float) else "int",
                        "propertyValueTimestamp": ts,
                        "propertyConnection": {"uri": asset_uri},
                    })
                return out

            if experiment_type == "breakage":
                agg = result.get("aggregate", {})
                test_data = {
                    "f1": agg.get("test_f1_mean"),
                    "precision": agg.get("test_precision_mean"),
                    "recall": agg.get("test_recall_mean"),
                    "n_samples": agg.get("n_folds"),
                }
                eval_data = {
                    "f1": agg.get("eval_f1_mean"),
                    "precision": agg.get("eval_precision_mean"),
                    "recall": agg.get("eval_recall_mean"),
                    "n_samples": agg.get("n_folds"),
                }
                delta_f1 = agg.get("delta_f1_mean", 0)
                pct_improve = agg.get("pct_f1_improvement", 0)
            else:
                test_data = result.get("test", {})
                eval_data = result.get("eval", {})
                comp = result.get("comparison", {})
                delta_f1 = comp.get("delta_f1", 0)
                pct_improve = comp.get("pct_f1_improvement", 0)

            test_f1 = test_data.get("f1", 0) or 0
            eval_f1 = eval_data.get("f1", 0) or 0

            # Create test phase asset
            await client.post_asset({
                "uri": test_uri,
                "label": f"Test Phase (F1={test_f1:.3f})",
                "assetType": _ASSET_TYPE,
                "assetDescription": "Baseline test phase — no feedback applied.",
            })
            for p in _phase_props("test", test_data, test_uri):
                await client.post_property(p)

            # Create eval phase asset
            await client.post_asset({
                "uri": eval_uri,
                "label": f"Eval Phase (F1={eval_f1:.3f})",
                "assetType": _ASSET_TYPE,
                "assetDescription": "Evaluation phase — with feedback loop.",
            })
            for p in _phase_props("eval", eval_data, eval_uri):
                await client.post_property(p)

            # Delta / improvement properties on experiment itself
            for key, value in [
                ("experiment_type", experiment_type),
                ("delta_f1", delta_f1),
                ("pct_f1_improvement", pct_improve),
            ]:
                if value is None:
                    continue
                str_val = str(round(value, 4)) if isinstance(value, float) else str(value)
                await client.post_property({
                    "uri": f"{exp_uri}:{key}",
                    "label": key.replace("_", " ").title(),
                    "propertyName": key,
                    "propertyValue": str_val,
                    "propertyUnit": "%" if "pct" in key else "",
                    "propertyDataType": "float" if isinstance(value, (int, float)) else "string",
                    "propertyValueTimestamp": ts,
                    "propertyConnection": {"uri": exp_uri},
                })

            # ── 3. Relationships (these are the graph edges GraphDB shows) ─
            # SINDIT expects URIRefNode objects ({"uri": "..."}) for source/target
            await client.post_relationship({
                "relationshipSource": {"uri": machine_uri},
                "relationshipTarget": {"uri": exp_uri},
                "relationshipType": "urn:lfl:rel:hasExperiment",
            })
            await client.post_relationship({
                "relationshipSource": {"uri": exp_uri},
                "relationshipTarget": {"uri": test_uri},
                "relationshipType": "urn:lfl:rel:hasTestPhase",
            })
            await client.post_relationship({
                "relationshipSource": {"uri": exp_uri},
                "relationshipTarget": {"uri": eval_uri},
                "relationshipType": "urn:lfl:rel:hasEvalPhase",
            })
            await client.post_relationship({
                "relationshipSource": {"uri": eval_uri},
                "relationshipTarget": {"uri": test_uri},
                "relationshipType": "urn:lfl:rel:improvedOver",
            })

            # ── 4. Operation nodes (from breakage folds) ────────────
            folds = result.get("folds", [])
            seen_ops: set = set()
            for fold in folds:
                op = fold.get("test_operation", "")
                if op and op not in seen_ops:
                    seen_ops.add(op)
                    op_uri = f"urn:lfl:operation:{op}"
                    await client.post_asset({
                        "uri": op_uri,
                        "label": f"Operation {op}",
                        "assetType": _ASSET_TYPE,
                        "assetDescription": f"Cutting operation {op} from experiment.",
                    })
                    await client.post_relationship({
                        "relationshipSource": {"uri": exp_uri},
                        "relationshipTarget": {"uri": op_uri},
                        "relationshipType": "urn:lfl:rel:analyzedOperation",
                    })
                    # Also link operation → machine
                    await client.post_relationship({
                        "relationshipSource": {"uri": machine_uri},
                        "relationshipTarget": {"uri": op_uri},
                        "relationshipType": "urn:lfl:rel:performedOperation",
                    })

            # ── 5. Pattern detection nodes ───────────────────────────
            pattern_counts: Dict[str, int] = {}
            for fold in folds:
                for phase_key in ("test", "eval"):
                    for sr in fold.get(phase_key, {}).get("sample_results", []):
                        for pat in (sr.get("detected_patterns") or []):
                            pattern_counts[pat] = pattern_counts.get(pat, 0) + 1

            # Also check stoppage-style results
            if not pattern_counts:
                for phase_key in ("test", "eval"):
                    for sr in result.get(phase_key, {}).get("sample_results", []):
                        for pat in (sr.get("detected_patterns") or []):
                            pattern_counts[pat] = pattern_counts.get(pat, 0) + 1

            for pat_key, count in pattern_counts.items():
                pat_uri = f"urn:lfl:pattern:{pat_key}"
                await client.post_asset({
                    "uri": pat_uri,
                    "label": pat_key.replace("_", " ").title(),
                    "assetType": _ASSET_TYPE,
                    "assetDescription": f"Pattern '{pat_key}' detected {count} times.",
                })
                await client.post_property({
                    "uri": f"{pat_uri}:detection_count:{run_id}",
                    "label": "Detection Count",
                    "propertyName": "detection_count",
                    "propertyValue": str(count),
                    "propertyUnit": "",
                    "propertyDataType": "int",
                    "propertyValueTimestamp": ts,
                    "propertyConnection": {"uri": pat_uri},
                })
                await client.post_relationship({
                    "relationshipSource": {"uri": exp_uri},
                    "relationshipTarget": {"uri": pat_uri},
                    "relationshipType": "urn:lfl:rel:detectedPattern",
                })

            n_nodes = 3 + len(seen_ops) + len(pattern_counts)  # exp + 2 phases + ops + patterns
            logger.info(
                "SINDIT: pushed %s experiment %s → %d KG nodes, %d relationships",
                experiment_type, run_id, n_nodes,
                4 + len(seen_ops) * 2 + len(pattern_counts),
            )

    except Exception:
        logger.warning("Failed to push experiment %s to SINDIT (non-fatal)", run_id, exc_info=True)


# Track active live runs so we can prevent duplicates and list them
_active_live_runs: Dict[str, asyncio.Task] = {}


@router.post("/experiment/run-live")
async def trigger_live_experiment(
    body: Dict[str, Any] = Body(default={}),
):
    """Run an experiment in-process with real-time progress via WebSocket.

    Returns immediately with ``{run_id, ws_url}`` so the client can connect
    to the progress WebSocket.  The experiment runs as a background task.

    Body parameters are merged into ExperimentConfig as overrides.
    """
    from .experiment_runner import LiveExperimentRunner

    run_id = body.pop("run_id", None) or f"stoppage_{datetime.now().strftime('%Y-%m-%d_%H%M')}"
    sandbox = body.pop("sandbox_priors", True)

    if run_id in _active_live_runs and not _active_live_runs[run_id].done():
        raise HTTPException(status_code=409, detail=f"Run {run_id} is already in progress")

    # ── Pre-flight: validate that the features CSV exists ────────────
    # Inline check — avoids importing ExperimentConfig (which fails
    # under uvicorn reload for unknown reasons).  Mirrors the naming
    # logic in ExperimentConfig.__post_init__.
    _win = float(body.get("window_size_s", 60.0))
    _gap = float(body.get("prediction_gap_s", 0.0))
    _win_tag = f"_w{int(_win)}s" if _win != 60.0 else ""
    _gap_tag = f"_gap{int(_gap)}s" if _gap > 0 else ""
    _csv_name = f"stoppage_features{_win_tag}{_gap_tag}.csv"
    import pathlib as _pl
    _csv_dir = _pl.Path(__file__).resolve().parent.parent.parent.parent / "data" / "breakage_patterns"
    _csv_path = _csv_dir / _csv_name
    if not _csv_path.exists():
        import glob as _glob
        avail = sorted(
            _pl.Path(p).name for p in _glob.glob(str(_csv_dir / "stoppage_features*.csv"))
        )
        raise HTTPException(
            status_code=422,
            detail=(
                f"Features CSV not found: {_csv_name}. "
                f"Either run feature extraction with "
                f"--window {int(_win)} --gap {int(_gap)}, "
                f"or choose parameters that match an existing file. "
                f"Available: {', '.join(avail) if avail else '(none)'}."
            ),
        )

    # ── Pre-flight: verify LLM connectivity ──────────────────────────
    _llm_ok = False
    _llm_model = ""
    _llm_provider = "groq"
    try:
        orch = get_orchestrator()
        if hasattr(orch, "explainer"):
            _llm_model = getattr(orch.explainer.config, "model", "")
            _llm_provider = getattr(orch.explainer.config, "provider", "groq")
            _llm_ok = orch.explainer.is_available()
    except Exception:
        pass

    logger.info(
        "[experiment:%s] Pre-flight: csv=%s (exists=%s), llm_provider=%s, llm_model=%s, llm_ok=%s",
        run_id, _csv_name, _csv_path.exists(), _llm_provider, _llm_model, _llm_ok,
    )

    runner = LiveExperimentRunner(
        config_overrides=body,
        run_id=run_id,
        sandbox_priors=sandbox,
    )

    async def _run_and_cleanup():
        from backend.events import bus
        logger.info("[experiment:%s] Background task started (config_overrides=%s)", run_id, body)
        # Give the client 1s to connect its WebSocket before we start
        # publishing progress events, preventing a race condition where
        # early errors are lost because nobody is subscribed yet.
        await asyncio.sleep(1.0)

        # Pre-experiment snapshot
