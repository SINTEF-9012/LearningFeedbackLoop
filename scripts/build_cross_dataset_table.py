#!/usr/bin/env python3
"""Assemble the cross-dataset summary table for §8.4 from the stored result JSONs.

Pulls the transfer/feedback headline numbers for all four datasets into one comparison
(task type, transfer axis, label quality, features, AUC), and emits both a console table
and a LaTeX table (`paper/cross_dataset_table.tex`). Reads only the committed result
artifacts — no re-run — so the table always matches the current data/*.json.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
OUT_TEX = ROOT / "paper" / "cross_dataset_table.tex"


def _load(p: Path):
    return json.loads(p.read_text()) if p.is_file() else None


def _rf(results: dict):
    """Pull the RandomForest pooled AUC + CI from a transfer_eval results dict."""
    for k, v in results.items():
        if "RandomForest" in k:
            return v.get("pooled_auc"), v.get("auc_ci95")
    return None, None


def collect() -> list:
    rows = []

    # --- Stoppage (pilot, weak labels) — transfer_results.json gap0 ---
    t = _load(DATA / "transfer_results.json")
    if t:
        auc, ci = _rf(t["stoppage_horizon"]["gap0s"]["results"])
        n = t["stoppage_horizon"]["gap0s"]["n_features_used"]
        rows.append(("Stoppage (SITE_A)", "onset detection", "operation", "weak",
                     f"{n}", auc, ci, "pilot"))
        # lead-time 30s if present
        if "gap30s" in t["stoppage_horizon"]:
            auc30, ci30 = _rf(t["stoppage_horizon"]["gap30s"]["results"])
            rows.append(("Stoppage (SITE_A)", "30s-lead prediction", "operation", "weak",
                         f"{n}", auc30, ci30, "pilot"))

    # --- Breakage (pilot, weak, 2 sessions) ---
    if t and "breakage" in t:
        auc, ci = _rf(t["breakage"]["results"])
        n = t["breakage"].get("n_features_used", "?")
        rows.append(("Breakage (Site_a_line2)", "pre-break prediction", "session (n=2)",
                     "weak", f"{n}", auc, ci, "pilot"))

    # --- figshare (public, measured tool life, 14 tools) — τ=0.2 ---
    f = _load(DATA / "figshare_transfer_results.json")
    if f:
        cell = f["sweep"].get("tau0.2") or next(iter(f["sweep"].values()))
        auc, ci = _rf(cell["results"])
        rows.append(("Tool-life (figshare)", "pre-failure prediction", "tool (n=14)",
                     "measured", f"{f['n_features']}", auc, ci, "public"))

    # --- Denkena (public, measured wear, 3 machines) — physical basis τ=100 ---
    d = _load(DATA / "denkena_transfer_physical.json") or _load(DATA / "denkena_transfer_results.json")
    if d:
        cell = d["sweep"].get("vb100") or next(iter(d["sweep"].values()))
        auc, ci = _rf(cell["results"])
        rows.append(("Wear (Denkena)", "wear-state classification", "machine (n=3)",
                     "measured", f"{d['n_features']}", auc, ci, "public"))
    return rows


def main() -> int:
    rows = collect()
    if not rows:
        sys.exit("no result JSONs found — run the transfer experiments first")

    # console
    print(f"{'dataset':<22}{'task':<26}{'transfer axis':<16}{'labels':<10}{'feat':>5}{'AUC':>8}  CI")
    print("-" * 100)
    for name, task, axis, lab, nf, auc, ci, _ in rows:
        cistr = f"[{ci[0]:.3f}, {ci[1]:.3f}]" if ci else ""
        print(f"{name:<22}{task:<26}{axis:<16}{lab:<10}{nf:>5}{auc:>8}  {cistr}")

    # LaTeX
    lines = [
        "% Auto-generated by scripts/build_cross_dataset_table.py — do not hand-edit.",
        "\\begin{table}[t]",
        "  \\caption{Transfer across all four datasets. Pilot datasets have weak (derived)",
        "  labels; the public reference datasets have measured tool-condition labels. AUC is",
        "  the RandomForest pooled leave-one-group-out transfer AUC (95\\% block-bootstrap CI).}",
        "  \\label{tab:cross-dataset}",
        "  \\small",
        "  \\begin{tabular}{llllrl}",
        "    \\toprule",
        "    Dataset & Task & Transfer axis & Labels & Feat. & Transfer AUC \\\\",
        "    \\midrule",
    ]
    last_kind = None
    for name, task, axis, lab, nf, auc, ci, kind in rows:
        if kind != last_kind:
            lines.append(f"    \\multicolumn{{6}}{{l}}{{\\emph{{{kind} datasets}}}} \\\\")
            last_kind = kind
        cistr = f"[{ci[0]:.2f}, {ci[1]:.2f}]" if ci else ""
        lines.append(f"    {name} & {task} & {axis} & {lab} & {nf} & "
                     f"{auc:.3f} {{\\footnotesize {cistr}}} \\\\")
    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}", ""]
    OUT_TEX.write_text("\n".join(lines))
    print(f"\nWrote LaTeX table -> {OUT_TEX.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
